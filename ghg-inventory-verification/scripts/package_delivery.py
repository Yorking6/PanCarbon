# -*- coding: utf-8 -*-
"""Stage 9 - delivery packaging (M5).

A delivery bundle is produced only when the Stage 7 reconciliation report is
clean. Every delivered file is listed with its role, byte size and SHA-256;
an evidence index and an AI-generation notice are included.
"""
from __future__ import annotations

import hashlib
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ghg_common import jsonable, load_json, write_json

REQUIRED_FILES: dict[str, str] = {
    "org_config.json": "runtime_configuration",
    "factor_library.json": "emission_factor_library",
    "activity_ledger.json": "signed_activity_ledger",
    "classification.json": "emission_source_classification",
    "matched.json": "method_and_factor_matching",
    "results.json": "machine_readable_results",
    "ghg_inventory.xlsx": "formula_driven_inventory",
    "formula_cache.json": "formula_expectation_cache",
    "report_manifest.json": "report_manifest",
    "checks.json": "reconciliation_report",
}
OPTIONAL_FILES: dict[str, str] = {
    "config_check.json": "stage0_configuration_check",
    "pending_ledger.json": "stage1_candidate_rows",
    "confirm_check.json": "stage2_confirmation_gate",
    "verification_signoff.json": "mode_b_human_signoff",
    "extraction_hint.json": "stage1_runtime_hint",
    "batch_signoff.json": "stage2_batch_signoff",
}
AIGC_NOTE = (
    "AI-assisted generation. Figures are reproducible from the supplied "
    "configuration, factor library and signed activity ledger; verify before "
    "external use. Verification conclusions are never generated by this tool."
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(str(path), "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _item(run: Path, name: str, role: str, required: bool) -> dict[str, Any]:
    path = run / name
    return {
        "path": name,
        "role": role,
        "required": required,
        "present": path.is_file(),
        "bytes": path.stat().st_size if path.is_file() else 0,
        "sha256": _sha256(path) if path.is_file() else None,
    }


def build_evidence_index(run: Path) -> dict[str, Any]:
    ledger = load_json(run / "activity_ledger.json")
    index: dict[str, list[str]] = {}
    for row in ledger.get("rows", []):
        for name in row.get("evidence_files", []) or []:
            index.setdefault(str(name), []).append(str(row.get("row_id")))
    payload = {
        "schema_version": "1.0",
        "row_count": len(ledger.get("rows", [])),
        "evidence_count": len(index),
        "evidence": [
            {"file": name, "rows": sorted(rows)}
            for name, rows in sorted(index.items())
        ],
    }
    write_json(run / "evidence_index.json", jsonable(payload))
    return payload


def deliver(run: Path, out: Path | None = None) -> dict[str, Any]:
    """Validate the run and produce a delivery bundle."""
    checks_path = run / "checks.json"
    checks = load_json(checks_path) if checks_path.is_file() else {}
    errors = list(checks.get("errors") or [])
    if checks.get("status") != "pass" or errors:
        return {
            "status": "blocked",
            "reason": "Stage 7 reconciliation is not clean; delivery refused",
            "checks_status": checks.get("status"),
            "checks_errors": len(errors),
            "items": [],
            "bundle": None,
        }

    manifest_path = run / "report_manifest.json"
    report_manifest = load_json(manifest_path) if manifest_path.is_file() else {}
    items: list[dict[str, Any]] = []
    for name, role in REQUIRED_FILES.items():
        items.append(_item(run, name, role, True))
    for name, role in OPTIONAL_FILES.items():
        if (run / name).is_file():
            items.append(_item(run, name, role, False))
    seen = {item["path"] for item in items}
    for document in report_manifest.get("documents", []):
        name = str(document.get("path") or "")
        if name and name not in seen:
            items.append(_item(run, name, "report_document", True))
            seen.add(name)
        for chart in document.get("chart_files", []) or []:
            if chart not in seen:
                items.append(_item(run, str(chart), "report_chart", True))
                seen.add(str(chart))

    missing = [item["path"] for item in items
               if item["required"] and not item["present"]]
    if missing:
        return {
            "status": "incomplete",
            "reason": "required deliverables are missing",
            "missing": missing,
            "items": items,
            "bundle": None,
        }

    results = load_json(run / "results.json")
    evidence = build_evidence_index(run)
    delivery: dict[str, Any] = {
        "schema_version": "1.0",
        "status": "pass",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "run_id": results.get("run_id"),
        "config_hash": results.get("config_hash"),
        "final_version_id": results.get("final_version_id"),
        "checks_status": checks.get("status"),
        "rules_run": list(checks.get("rules_run") or []),
        "rules_deferred": dict(checks.get("rules_deferred") or {}),
        "total_tco2e": next(
            (v.get("total") for v in results.get("versions", [])
             if v.get("version_id") == results.get("final_version_id")), None),
        "evidence_count": evidence["evidence_count"],
        "aigc_note": AIGC_NOTE,
        "items": items,
        "warnings": list(checks.get("warnings") or []),
        "bundle": None,
    }

    target = out or (run / "delivery" /
                     f"{str(results.get('run_id') or 'run')}_delivery.zip")
    target.parent.mkdir(parents=True, exist_ok=True)
    write_json(run / "delivery_manifest.json", jsonable(delivery))
    with zipfile.ZipFile(str(target), "w", zipfile.ZIP_DEFLATED) as archive:
        for item in items:
            archive.write(str(run / item["path"]), arcname=item["path"])
        archive.write(str(run / "delivery_manifest.json"),
                      arcname="delivery_manifest.json")
        archive.write(str(run / "evidence_index.json"),
                      arcname="evidence_index.json")
    delivery["bundle"] = str(target)
    write_json(run / "delivery_manifest.json", jsonable(delivery))
    return delivery
